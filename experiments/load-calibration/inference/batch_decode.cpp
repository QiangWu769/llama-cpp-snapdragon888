using Clock = std::chrono::steady_clock;

static uint64_t qtimer_ns() {
#if defined(__aarch64__)
    uint64_t ticks, frequency;
    asm volatile("isb\n\tmrs %0, cntvct_el0\n\tmrs %1, cntfrq_el0"
                 : "=r"(ticks), "=r"(frequency) : : "memory");
    return uint64_t((__uint128_t(ticks) * 1000000000u) / frequency);
#else
    throw std::runtime_error("This research clock needs AArch64 CNTVCT");
#endif
}
struct Phase { const char *name; uint64_t start, end; };

struct Options {
    std::string model;
    std::string prompt = "The capital of France is";
    std::string prompts_file;
    int parallel = 4;
    int tokens = 32;
    int threads = 4;
    int context_per_sequence = 256;
    bool ignore_eos = false;
    bool reuse_cpu_threadpool = false;
};

int positive_integer(const std::string &text, const char *label, int maximum) {
    size_t consumed = 0;
    int value = std::stoi(text, &consumed);
    if (consumed != text.size() || value < 1 || value > maximum)
        throw std::invalid_argument(std::string(label) + " outside its positive range");
    return value;
}

Options parse(int argc, char **argv) {
    Options options;
    for (int index = 1; index < argc; index++) {
        std::string key = argv[index];
        if (key == "--ignore-eos") { options.ignore_eos = true; continue; }
        if (key == "--reuse-cpu-threadpool") { options.reuse_cpu_threadpool = true; continue; }
        if (index + 1 >= argc) throw std::invalid_argument("missing argument for " + key);
        std::string value = argv[++index];
        if (key == "--model") options.model = value;
        else if (key == "--parallel") options.parallel = positive_integer(value, "parallel", 32);
        else if (key == "--tokens") options.tokens = positive_integer(value, "tokens", 512);
        else if (key == "--threads") options.threads = positive_integer(value, "threads", 8);
        else if (key == "--context-per-sequence") options.context_per_sequence = positive_integer(value, "context", 4096);
        else if (key == "--prompt") options.prompt = value;
        else if (key == "--prompts-file") options.prompts_file = value;
        else throw std::invalid_argument("unknown option " + key);
    }
    if (options.model.empty()) throw std::invalid_argument("--model is required");
    if (std::getenv("SKIP_HTP_OPS"))
        throw std::invalid_argument("SKIP_HTP_OPS cannot be used with permuted HMX FP16 weights");
    return options;
}

std::string quote(const std::string &text) {
    // Preserve valid UTF-8; replace incomplete/invalid byte sequences in text.
    // output_bytes_hex separately preserves the exact generated bytes.
    std::ostringstream output;
    output << '"';
    for (size_t index = 0; index < text.size();) {
        auto byte = static_cast<unsigned char>(text[index]);
        if (byte < 0x80) {
            if (byte == '"' || byte == '\\') output << '\\' << text[index];
            else if (byte < 0x20) output << "\\u" << std::hex << std::setw(4)
                << std::setfill('0') << int(byte) << std::dec;
            else output << text[index];
            index++;
            continue;
        }
        size_t count = byte >= 0xC2 && byte <= 0xDF ? 2
                     : byte >= 0xE0 && byte <= 0xEF ? 3
                     : byte >= 0xF0 && byte <= 0xF4 ? 4 : 0;
        bool valid = count && index + count <= text.size();
        if (valid) {
            for (size_t next = 1; next < count; next++) {
                auto continuation = static_cast<unsigned char>(text[index + next]);
                valid = valid && continuation >= 0x80 && continuation <= 0xBF;
            }
            auto second = static_cast<unsigned char>(text[index + 1]);
            if ((byte == 0xE0 && second < 0xA0) || (byte == 0xED && second >= 0xA0)
                || (byte == 0xF0 && second < 0x90) || (byte == 0xF4 && second >= 0x90)) valid = false;
        }
        if (valid) { output << text.substr(index, count); index += count; }
        else { output << "\\ufffd"; index++; }
    }
    output << '"';
    return output.str();
}

std::string hex_bytes(const std::string &text) {
    std::ostringstream output;
    for (unsigned char byte : text)
        output << std::hex << std::setw(2) << std::setfill('0') << int(byte);
    return output.str();
}

std::vector<llama_token> tokenize(llama_model *model, const std::string &text) {
    if (text.size() > size_t(std::numeric_limits<int32_t>::max()))
        throw std::invalid_argument("prompt too large");
    int count = llama_tokenize(model, text.data(), int32_t(text.size()), nullptr, 0, true, true);
    if (count >= 0) throw std::runtime_error("empty prompt or unexpected token sizing result");
    std::vector<llama_token> tokens(size_t(-count));
    count = llama_tokenize(model, text.data(), int32_t(text.size()), tokens.data(),
                           int32_t(tokens.size()), true, true);
    if (count <= 0) throw std::runtime_error("prompt tokenization failed");
    tokens.resize(size_t(count));
    return tokens;
}

std::string token_piece(llama_model *model, llama_token token) {
    char local[256];
    int count = llama_token_to_piece(model, token, local, sizeof(local), 0, false);
    if (count >= 0) return std::string(local, size_t(count));
    std::vector<char> expanded(size_t(-count));
    count = llama_token_to_piece(model, token, expanded.data(), int32_t(expanded.size()), 0, false);
    if (count < 0) throw std::runtime_error("token conversion failed");
    return std::string(expanded.data(), size_t(count));
}

struct Batch {
    llama_batch value;
    explicit Batch(int capacity) : value(llama_batch_init(capacity, 0, 1)) {}
    ~Batch() { llama_batch_free(value); }
    Batch(const Batch &) = delete;
    Batch &operator=(const Batch &) = delete;
    void clear() { value.n_tokens = 0; }
    void add(llama_token token, llama_pos position, llama_seq_id sequence, bool logits) {
        int index = value.n_tokens++;
        value.token[index] = token;
        value.pos[index] = position;
        value.n_seq_id[index] = 1;
        value.seq_id[index][0] = sequence;
        value.logits[index] = logits;
    }
};

struct Sequence {
    std::string prompt, output;
    std::vector<llama_token> prompt_tokens, generated;
    std::unique_ptr<llama_sampler, decltype(&llama_sampler_free)> sampler{nullptr, llama_sampler_free};
    int logits_index = -1;
    int eos_step = -1;
    bool finished = false;
};

double seconds(Clock::duration duration) {
    return std::chrono::duration<double>(duration).count();
}

int run(const Options &options) {
    std::unique_ptr<llama_model, decltype(&llama_free_model)> model(
        llama_load_model_from_file(options.model.c_str(), llama_model_default_params()), llama_free_model);
    if (!model) throw std::runtime_error("model load failed");
    if (llama_model_has_encoder(model.get())) throw std::runtime_error("decoder-only model required");

    std::vector<std::string> prompts;
    if (!options.prompts_file.empty()) {
        std::ifstream input(options.prompts_file);
        if (!input) throw std::runtime_error("cannot read prompts file");
        std::string line;
        while (std::getline(input, line)) {
            if (!line.empty() && line.back() == '\r') line.pop_back();
            prompts.push_back(line);
        }
        if (prompts.size() != size_t(options.parallel))
            throw std::invalid_argument("prompts file must contain exactly parallel lines");
    } else prompts.assign(size_t(options.parallel), options.prompt);

    std::vector<Sequence> sequences(size_t(options.parallel));
    int maximum_prompt = 0;
    int total_prompt = 0;
    for (int index = 0; index < options.parallel; index++) {
        auto &sequence = sequences[size_t(index)];
        sequence.prompt = prompts[size_t(index)];
        sequence.prompt_tokens = tokenize(model.get(), sequence.prompt);
        maximum_prompt = std::max(maximum_prompt, int(sequence.prompt_tokens.size()));
        total_prompt += int(sequence.prompt_tokens.size());
        sequence.sampler.reset(llama_sampler_init_greedy());
        if (!sequence.sampler) throw std::runtime_error("sampler allocation failed");
    }
    if (maximum_prompt + options.tokens + 1 > options.context_per_sequence)
        throw std::invalid_argument("context per sequence cannot hold prompt and output; increase it explicitly");

    auto parameters = llama_context_default_params();
    parameters.n_ctx = uint32_t(options.parallel * options.context_per_sequence);
    parameters.n_seq_max = uint32_t(options.parallel);
    parameters.n_batch = uint32_t(std::max({32, total_prompt, options.parallel}));
    parameters.n_ubatch = uint32_t(options.parallel);
    parameters.n_threads = options.threads;
    parameters.n_threads_batch = options.threads;
    parameters.flash_attn = true;
    parameters.no_perf = false;
    // Context destruction must precede freeing its externally owned CPU pool.
    // This owner is declared first so reverse RAII destruction preserves that
    // ordering on every exit, including allocation/decode exceptions.
    std::unique_ptr<ggml_threadpool, decltype(&ggml_threadpool_free)> cpu_threadpool(
        nullptr, ggml_threadpool_free);
    std::unique_ptr<llama_context, decltype(&llama_free)> context(
        llama_new_context_with_model(model.get(), parameters), llama_free);
    if (!context) throw std::runtime_error("context creation failed");
    if (llama_n_ubatch(context.get()) < uint32_t(options.parallel))
        throw std::runtime_error("physical microbatch is smaller than requested simultaneous width");
    if (options.reuse_cpu_threadpool) {
        auto pool_parameters = ggml_threadpool_params_default(options.threads);
        cpu_threadpool.reset(ggml_threadpool_new(&pool_parameters));
        if (!cpu_threadpool) throw std::runtime_error("ordinary CPU threadpool allocation failed");
        llama_attach_threadpool(context.get(), cpu_threadpool.get(), cpu_threadpool.get());
        std::cerr << "batch_decode: ordinary CPU threadpool attached (threads="
                  << options.threads << ")\n";
    }

    Batch batch(std::max(total_prompt, options.parallel));
    for (int sequence_id = 0; sequence_id < options.parallel; sequence_id++) {
        auto &sequence = sequences[size_t(sequence_id)];
        for (size_t token = 0; token < sequence.prompt_tokens.size(); token++) {
            bool last = token + 1 == sequence.prompt_tokens.size();
            sequence.logits_index = last ? batch.value.n_tokens : sequence.logits_index;
            batch.add(sequence.prompt_tokens[token], llama_pos(token), sequence_id, last);
        }
    }
    std::vector<Phase> phases;
    uint64_t prefill_qtimer = qtimer_ns();
    auto prefill_started = Clock::now();
    int code = llama_decode(context.get(), batch.value);
    llama_synchronize(context.get());
    if (code) throw std::runtime_error("prefill decode failed: " + std::to_string(code));
    double prefill_seconds = seconds(Clock::now() - prefill_started);
    phases.push_back({"prefill", prefill_qtimer, qtimer_ns()});

    uint64_t decode_input_tokens = 0, output_tokens = 0, decode_calls = 0;
    double decode_backend_seconds = 0;
    std::map<int, uint64_t> widths;
    uint64_t generation_qtimer = qtimer_ns();
    auto generation_started = Clock::now();
    for (int step = 0; step < options.tokens; step++) {
        batch.clear();
        for (int sequence_id = 0; sequence_id < options.parallel; sequence_id++) {
            auto &sequence = sequences[size_t(sequence_id)];
            if (sequence.finished) continue;
            llama_token token = llama_sampler_sample(sequence.sampler.get(), context.get(), sequence.logits_index);
            if (llama_token_is_eog(model.get(), token) && !options.ignore_eos) {
                sequence.eos_step = step;
                sequence.finished = true;
                continue;
            }
            sequence.generated.push_back(token);
            sequence.output += token_piece(model.get(), token);
            output_tokens++;
            if (step + 1 == options.tokens) continue;
            sequence.logits_index = batch.value.n_tokens;
            batch.add(token, llama_pos(sequence.prompt_tokens.size() + size_t(step)), sequence_id, true);
        }
        if (!batch.value.n_tokens) break;
        widths[batch.value.n_tokens]++;
        decode_calls++;
        decode_input_tokens += uint64_t(batch.value.n_tokens);
        uint64_t decode_qtimer = qtimer_ns();
        auto decoded_started = Clock::now();
        code = llama_decode(context.get(), batch.value);
        llama_synchronize(context.get());
        decode_backend_seconds += seconds(Clock::now() - decoded_started);
        phases.push_back({"decode_call", decode_qtimer, qtimer_ns()});
        if (code) throw std::runtime_error("generation decode failed: " + std::to_string(code));
    }
    double generation_seconds = seconds(Clock::now() - generation_started);
    phases.push_back({"generation", generation_qtimer, qtimer_ns()});
    std::ostringstream json;
    json << std::setprecision(17)
         << "{\"schema_version\":1,\"mode\":\"independent_sequence_decode\",\"model\":" << quote(options.model)
         << ",\"parallel_requested\":" << options.parallel << ",\"tokens_limit_per_sequence\":" << options.tokens
         << ",\"ignore_eos\":" << (options.ignore_eos ? "true" : "false")
         << ",\"sampling\":\"independent_greedy\",\"context_total_actual\":" << llama_n_ctx(context.get())
         << ",\"sequence_capacity_actual\":" << llama_n_seq_max(context.get())
         << ",\"logical_batch_actual\":" << llama_n_batch(context.get())
         << ",\"physical_microbatch_actual\":" << llama_n_ubatch(context.get())
         << ",\"threads\":" << options.threads << ",\"prefill_tokens\":" << total_prompt
         << ",\"reuse_cpu_threadpool\":" << (options.reuse_cpu_threadpool ? "true" : "false")
         << ",\"cpu_threadpool_threads\":";
    if (cpu_threadpool) json << options.threads; else json << "null";
    json
         << ",\"prefill_seconds\":" << prefill_seconds << ",\"generation_wall_seconds\":" << generation_seconds
         << ",\"decode_backend_seconds\":" << decode_backend_seconds << ",\"decode_calls\":" << decode_calls
         << ",\"decode_input_tokens\":" << decode_input_tokens << ",\"output_tokens\":" << output_tokens
         << ",\"aggregate_output_tokens_per_second\":";
    if (generation_seconds > 0) json << output_tokens / generation_seconds; else json << "null";
    json << ",\"decode_input_tokens_per_second\":";
    if (decode_backend_seconds > 0) json << decode_input_tokens / decode_backend_seconds; else json << "null";
    json << ",\"phase_clock\":\"CNTVCT_ns\",\"phases\":[";
    for (size_t i=0; i<phases.size(); ++i) {
        if (i) json << ',';
        json << "{\"name\":" << quote(phases[i].name) << ",\"start_ns\":" << phases[i].start
             << ",\"end_ns\":" << phases[i].end << '}';
    }
    json << "],\"decode_batch_histogram\":{";
    bool first = true;
    for (const auto &item : widths) {
        if (!first) json << ',';
        first = false;
        json << quote(std::to_string(item.first)) << ':' << item.second;
    }
    json << "},\"sequences\":[";
    for (int index = 0; index < options.parallel; index++) {
        if (index) json << ',';
        const auto &sequence = sequences[size_t(index)];
        json << "{\"seq_id\":" << index << ",\"prompt\":" << quote(sequence.prompt)
             << ",\"prompt_tokens\":" << sequence.prompt_tokens.size()
             << ",\"eos_step\":" << sequence.eos_step << ",\"generated_tokens\":" << sequence.generated.size()
             << ",\"output_text\":" << quote(sequence.output) << ",\"output_bytes_hex\":" << quote(hex_bytes(sequence.output))
             << ",\"token_ids\":[";
        for (size_t token = 0; token < sequence.generated.size(); token++) {
            if (token) json << ',';
            json << sequence.generated[token];
        }
        json << "]}";
    }
    json << "],\"timing_note\":\"First output token uses prefill logits. Output throughput includes sampling; decode input throughput counts only timed decode inputs. Histogram is submitted llama_decode token count; confirm HMX tensor M in backend traces.\"}";
    std::cout << json.str() << '\n';
    llama_perf_context_print(context.get());
    return 0;
}

int main(int argc, char **argv) {
    try {
        auto options = parse(argc, argv);
        llama_backend_init();
        try {
            int result = run(options);
            llama_backend_free();
            return result;
        } catch (...) {
            llama_backend_free();
            throw;
        }
    } catch (const std::exception &error) {
        std::cerr << "batch_decode: " << error.what() << '\n';
        return 1;
    }
}
